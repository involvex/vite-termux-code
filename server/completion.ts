/**
 * Shell completion for td-code.
 *
 * `td-code completion bash` prints a self-contained bash script to stdout.
 * Install it with:
 *   td-code completion bash | sudo tee /etc/bash_completion.d/td-code >/dev/null
 * or for the current shell only:
 *   source <(td-code completion bash)
 *
 * The script itself is plain bash in single-quoted lines (no ${} interpolation
 * hazards): flags, subcommands, config-init flags, and directory names.
 */

export const SUPPORTED_COMPLETION_SHELLS = ['bash'] as const
export type CompletionShell = (typeof SUPPORTED_COMPLETION_SHELLS)[number]

export function isCompletionShell(s: string): s is CompletionShell {
	return (SUPPORTED_COMPLETION_SHELLS as readonly string[]).includes(s)
}

const LINES = [
	'# td-code bash completion (generated by `td-code completion bash`)',
	'# Install system-wide:',
	'#   td-code completion bash | sudo tee /etc/bash_completion.d/td-code >/dev/null',
	'# or for the current shell only:',
	'#   source <(td-code completion bash)',
	'_td_code() {',
	'	local cur prev words cword',
	'	if declare -F _init_completion >/dev/null 2>&1; then',
	'		_init_completion -n : || return',
	'	else',
	'		cur="${COMP_WORDS[COMP_CWORD]}"',
	'		prev="${COMP_WORDS[COMP_CWORD-1]}"',
	'		words=("${COMP_WORDS[@]}")',
	'		cword=$COMP_CWORD',
	'	fi',
	'',
	'	local value_flags="-p --port --host --auth-token --pairing-code"',
	'	local top_flags="$value_flags --no-auth --pairing --no-watch --no-terms --open -h --help -v --version"',
	'',
	'	# Flags that take a value: complete the value position, not the next flag.',
	'	case "$prev" in',
	'		--host) COMPREPLY=($(compgen -W "127.0.0.1 0.0.0.0 localhost" -- "$cur")); return 0;;',
	'		-p|--port|--auth-token|--pairing-code) return 0;;',
	'	esac',
	'',
	'	# Locate the subcommand: first bare word, skipping flags and their values.',
	'	local i=1 sub="" skip_next=0 w',
	'	while [ $i -lt $cword ]; do',
	'		w="${words[i]}"',
	'		if [ $skip_next -eq 1 ]; then',
	'			skip_next=0',
	'		elif [[ "$w" == -* ]]; then',
	'			case "$w" in -p|--port|--host|--auth-token|--pairing-code) skip_next=1;; esac',
	'		elif [ -z "$sub" ]; then',
	'			sub="$w"',
	'		fi',
	'		i=$((i+1))',
	'	done',
	'',
	'	case "$sub" in',
	'		config)',
	'			# First bare word after `config` is the config subcommand.',
	'			local j=1 seen=0 subsub=""',
	'			while [ $j -lt $cword ]; do',
	'				w="${words[j]}"',
	'				if [ $seen -eq 1 ] && [[ "$w" != -* ]] && [ -z "$subsub" ]; then',
	'					subsub="$w"',
	'				elif [ "$w" = "config" ]; then',
	'					seen=1',
	'				fi',
	'				j=$((j+1))',
	'			done',
	'			case "$subsub" in',
	'				"") COMPREPLY=($(compgen -W "init edit validate path" -- "$cur"));;',
	'				init)',
	'					if [[ "$cur" == -* ]]; then',
	'						COMPREPLY=($(compgen -W "--force -f" -- "$cur"))',
	'					fi;;',
	'				*) ;;',
	'			esac',
	'			return 0;;',
	'		completion)',
	'			COMPREPLY=($(compgen -W "bash" -- "$cur"))',
	'			return 0;;',
	'		"")',
	'			if [[ "$cur" == -* ]]; then',
	'				COMPREPLY=($(compgen -W "$top_flags config completion" -- "$cur"))',
	'			else',
	'				_td_code_dirs',
	'				COMPREPLY+=($(compgen -W "config completion" -- "$cur"))',
	'			fi',
	'			return 0;;',
	'		*)',
	'			# A directory argument (or typo): keep completing flags and dirs.',
	'			if [[ "$cur" == -* ]]; then',
	'				COMPREPLY=($(compgen -W "$top_flags" -- "$cur"))',
	'			else',
	'				_td_code_dirs',
	'			fi',
	'			return 0;;',
	'	esac',
	'}',
	'',
	'# Directory matches with a trailing slash so completion continues inside.',
	'_td_code_dirs() {',
	'	local d',
	'	COMPREPLY=()',
	'	while IFS= read -r d; do',
	'		[ -d "$d" ] && d="$d/"',
	'		COMPREPLY+=("$d")',
	'	done < <(compgen -d -- "$cur")',
	'}',
	'',
	'complete -F _td_code -o default td-code',
	'',
]

/** The full bash completion script, trailing newline included. */
export function bashCompletionScript(): string {
	return `${LINES.join('\n')}\n`
}
